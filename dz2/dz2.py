A, B, C = 1.0, 1e8, 1.0
D = math.sqrt(B * B - 4 * A * C)
x_big = (-B - D) / (2 * A)
x_small_naive = (-B + D) / (2 * A)          # вычитание близких чисел: −1e8 + 99999999.99999998
x_small_stable = (2 * C) / (-B - D)          # то же самое через формулу Виета: x1·x2 = c/a
